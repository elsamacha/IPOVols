"""Is the full model worth it? Out-of-sample comparison against simpler models.

    python scripts/model_comparison.py

For each synthetic universe, every IPO is priced by a model calibrated without it
(5-fold), at 5 and 21 trading days after listing. Methods:

  B0      peer 30d implied vol, no premium
  B1      peer vol x average IPO premium at that age (age-only curve, no features, no events)
  LR      linear regression of log(IPO var / peer var) on deal features + an event-in-window dummy
  model   the full structural model
  oracle  the true expected value (knows every parameter, including each IPO's idiosyncratic
          level). Only the noise remains, so it is the ceiling no method can beat.

Universes:
  "own"   generated by the model's own equations (favourable to the model)
  "alt"   power-law decay, no earnings step, nonlinear feature effects (misspecified)
  "alt60" same as alt with only 60 IPOs (closer to the real sample size)
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ipovol.backtest import backtest, summarize
from ipovol.synthetic import generate, TRUTH


def add_oracle(res, extras):
    res = res.copy()
    res["iv_oracle"] = [extras["iv_true"][r.ticker].loc[r.asof] for r in res.itertuples()]
    rv = []
    for r in res.itertuples():
        v = extras["v_true"][r.ticker]
        i = v.index.get_loc(r.asof)
        rv.append(np.sqrt(v.iloc[i + 1: i + 22].mean() * 252))
    res["rv_oracle"] = rv
    return res


def scores(res):
    return summarize(res, methods=("B0", "B1", "LR", "model", "oracle"))


def run(name, n, form):
    deals, px, earnings, extras = generate(n_ipo=n, seed=7, truth=dict(TRUTH, form=form))
    res, _ = backtest(deals, px, earnings, origins=(5, 21), folds=5, verbose=False)
    s = scores(add_oracle(res, extras))
    s.insert(0, "universe", name)
    return s


if __name__ == "__main__":
    out = pd.concat([run("own", 160, "exp"), run("alt", 160, "alt"), run("alt60", 60, "alt")])
    pd.set_option("display.width", 200)
    print(out.drop(columns=["qlike"]).round(3).to_string(index=False))
    (ROOT / "output").mkdir(exist_ok=True)
    out.to_csv(ROOT / "output" / "model_comparison.csv", index=False)
